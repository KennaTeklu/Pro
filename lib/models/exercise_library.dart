import 'muscle.dart';

class ExerciseDefinition {
  final String name;
  final List<String> muscles;
  final String equipment;
  final int defaultSets;
  final String defaultReps;
  final String progression;
  final List<String> instructions;
  final double strengthIndex;      // expected 1RM / bodyweight
  final double skillFactor;        // technical difficulty (0.5–1.0)
  final String genderSuitability;  // 'both', 'male', 'female'
  final String prescriptionType;   // 'reps', 'time', 'amrap'
  final int? defaultDuration;      // for time‑based

  ExerciseDefinition({
    required this.name,
    required this.muscles,
    required this.equipment,
    required this.defaultSets,
    required this.defaultReps,
    required this.progression,
    required this.instructions,
    required this.strengthIndex,
    required this.skillFactor,
    required this.genderSuitability,
    required this.prescriptionType,
    this.defaultDuration,
  });
}

